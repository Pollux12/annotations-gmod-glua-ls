function constraint.AdvBallsocket(ent1, ent2, bone1, bone2, localPos1, localPos2, forceLimit, torqueLimit, xMin, yMin, zMin, xMax, yMax, zMax, xFric, yFric, zFric, onlyRotation, noCollide) end
